/** Deterministic seeded RNG (mulberry32). Shared by all game logic for reproducible tests. */
export class RNG {
  private s: number;

  constructor(seed = 123456789) {
    this.s = seed >>> 0;
  }

  /** Float in [0,1). */
  next(): number {
    this.s = (this.s + 0x6d2b79f5) >>> 0;
    let t = this.s;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }

  range(min: number, max: number): number {
    return min + (max - min) * this.next();
  }

  int(maxExclusive: number): number {
    return Math.floor(this.next() * maxExclusive);
  }

  chance(p: number): boolean {
    return this.next() < p;
  }

  pick<T>(arr: readonly T[]): T {
    return arr[this.int(arr.length)];
  }

  /** Weighted pick. weights need not sum to 1. */
  weighted<T>(items: readonly T[], weights: readonly number[]): T {
    let total = 0;
    for (const w of weights) total += w;
    let r = this.next() * total;
    for (let i = 0; i < items.length; i++) {
      r -= weights[i];
      if (r <= 0) return items[i];
    }
    return items[items.length - 1];
  }
}

/** Global gameplay RNG; seeded for tests, time-based at runtime. */
export const rng = new RNG();

export function reseedRng(seed: number): void {
  // mutate the shared instance in place so module references stay valid
  (rng as unknown as { s: number }).s = seed >>> 0;
}
